"""Independent regressions for joint-period torus grids."""

from fractions import Fraction
from itertools import product

import numpy as np
import pytest
from scipy.linalg import expm

from gudhi.datasets.linear_orbits import sample_from_lie_group_rep
from gudhi.liedetect import OrbitFitter
from gudhi.liedetect.algebra import get_canonical_pushforward_algebra
from gudhi.liedetect.utils import (
    _integer_column_lattice_basis,
    _joint_period_generators,
    sample_orbit_from_algebra_torus,
)


def _angular_grid(width, dimension):
    return np.array(list(product(np.arange(width) * (2 * np.pi / width), repeat=dimension)))


def _rotation_points(angles, weights):
    phases = angles @ np.asarray(weights)
    return np.stack((np.cos(phases), -np.sin(phases)), axis=-1).reshape(len(angles), -1)


def _distinct(points):
    return len(np.unique(points.round(10), axis=0))


def test_index_two_presentation_no_longer_repeats_grid_transformations():
    weights = ((1, 1), (1, -1))
    old_points = _rotation_points(_angular_grid(4, 2), weights)
    assert _distinct(old_points) == 8

    base = np.array([1.0, 0.0, 1.0, 0.0])
    points = sample_from_lie_group_rep("torus", weights, 16, x=base)
    # The quotient in this square full-rank case covers both phase circles.
    expected = _rotation_points(_angular_grid(4, 2), np.eye(2))
    assert _distinct(points) == 16
    assert {tuple(point) for point in points.round(10)} == {
        tuple(point) for point in expected.round(10)
    }


def test_exact_column_lattice_basis_and_joint_periods():
    weights = ((1, 1, 2, 0), (1, -1, 0, 2))
    basis = _integer_column_lattice_basis(weights)
    # A unimodular transformation of the generating columns preserves the basis.
    permuted = tuple(tuple(-row[i] if i % 2 else row[i] for i in [3, 2, 1, 0]) for row in weights)
    assert _integer_column_lattice_basis(permuted) == basis
    (a, b), (c, d) = basis
    determinant = a * d - b * c
    assert determinant == 2
    # All columns lie in the basis lattice. The determinant and parity then
    # identify exactly the index-two lattice generated by the input columns.
    assert all((u - v) % 2 == 0 for u, v in zip(*basis))
    inverse = ((Fraction(d, determinant), Fraction(-b, determinant)),
               (Fraction(-c, determinant), Fraction(a, determinant)))
    for row in inverse:
        assert all(sum(coefficient * value for coefficient, value in zip(row, column)).denominator == 1
                   for column in zip(*weights))
    algebra = get_canonical_pushforward_algebra("torus", weights)
    for generator in _joint_period_generators(weights, algebra):
        np.testing.assert_allclose(expm(generator), np.eye(8), atol=1e-12)


def test_joint_grid_with_conjugated_and_rescaled_generators():
    weights = ((1, 1), (1, -1))
    base = np.array([1.0, 0.0, 1.0, 0.0])
    generators = get_canonical_pushforward_algebra("torus", weights)
    q, _ = np.linalg.qr(np.random.default_rng(7).normal(size=(4, 4)))
    changed = [scale * (q @ mat @ q.T) for scale, mat in zip((2.0, 0.25), generators)]
    original = sample_orbit_from_algebra_torus(weights, generators, base, 16)
    points = sample_orbit_from_algebra_torus(weights, changed, q @ base, 16)
    np.testing.assert_allclose(points, original @ q.T, atol=1e-12)
    assert _distinct(points) == 16


@pytest.mark.parametrize(
    ("weights", "expected_weights", "width"),
    [(((2, 4),), ((1, 2),), 9), (((2, 0), (0, 3)), ((1, 0), (0, 1)), 4)],
)
def test_axis_aligned_period_grids_keep_their_coordinates(weights, expected_weights, width):
    dimension = len(weights)
    base = np.tile([1.0, 0.0], len(weights[0]))
    points = sample_from_lie_group_rep("torus", weights, width**dimension, x=base)
    expected = _rotation_points(_angular_grid(width, dimension), expected_weights)
    np.testing.assert_allclose(points, expected, atol=1e-12)


def test_seeded_random_uses_the_original_axis_period_rectangle():
    weights = ((1, 1), (1, -1))
    base = np.array([1.0, 0.0, 1.0, 0.0])
    count = 17
    expected_angles = 2 * np.pi * np.random.default_rng(11).random((count, 2))
    expected = _rotation_points(expected_angles, weights)
    points = sample_from_lie_group_rep(
        "torus", weights, count, x=base, method="random_uniform", seed=11
    )
    np.testing.assert_allclose(points, expected, atol=1e-12)


def test_redundant_generators_and_constant_deterministic_orbit():
    independent = ((1, 1), (1, -1))
    redundant = ((0, 0), (1, 1), (2, 2), (1, -1))
    base = np.array([1.0, 0.0, 1.0, 0.0])
    expected = sample_from_lie_group_rep("torus", independent, 16, x=base)
    points = sample_from_lie_group_rep("torus", redundant, 16, x=base)
    np.testing.assert_allclose(points, expected, atol=1e-12)
    constant = sample_from_lie_group_rep("torus", ((0, 0),), 7, x=base)
    np.testing.assert_array_equal(constant, np.tile(base, (7, 1)))


def test_image_grid_does_not_quotient_a_base_point_stabilizer():
    weights = ((1, 0, 1), (0, 2, 1))
    active = sample_from_lie_group_rep("torus", weights, 16, x=np.tile([1.0, 0], 3))
    inactive = sample_from_lie_group_rep(
        "torus", weights, 16, x=np.array([1.0, 0, 1.0, 0, 0, 0])
    )
    assert _distinct(active) == 16
    assert _distinct(inactive) == 8


def test_orbit_fitter_reconstruction_uses_joint_periods():
    weights = ((1, 1), (1, -1))
    angles = np.random.default_rng(21).uniform(0, 2 * np.pi, (100, 2))
    fitter = OrbitFitter(_rotation_points(angles, weights))
    fitter.lie_pca(10, 2)
    fitter.closest_algebra(
        "torus", method="full_lie_pca", reps_to_test=[weights], initial_point=np.eye(4)
    )
    assert _distinct(fitter.sample_orbit(16)) == 16
    thinned = fitter.sample_orbit(15)
    assert thinned.shape == (15, 4)
    assert _distinct(thinned) == 15
